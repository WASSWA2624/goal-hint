CREATE TABLE `MemberPasswordResetRequest` (
  `id` CHAR(36) NOT NULL,
  `accountId` CHAR(36) NOT NULL,
  `phone` VARCHAR(15) NOT NULL,
  `status` VARCHAR(16) NOT NULL,
  `requestedAt` DATETIME(3) NOT NULL,
  `ownershipVerifiedAt` DATETIME(3) NULL,
  `ownershipVerifiedBy` CHAR(36) NULL,
  `ownershipMethod` VARCHAR(8) NULL,
  `generatedAt` DATETIME(3) NULL,
  `generatedBy` CHAR(36) NULL,
  `expiresAt` DATETIME(3) NULL,
  `generation` INTEGER UNSIGNED NOT NULL DEFAULT 0,
  `tokenHash` CHAR(64) NULL,
  `tokenCiphertext` VARCHAR(128) NULL,
  `markedSentAt` DATETIME(3) NULL,
  `markedSentBy` CHAR(36) NULL,
  `markedSentChannel` VARCHAR(8) NULL,
  `completedAt` DATETIME(3) NULL,
  `cancelledAt` DATETIME(3) NULL,
  UNIQUE INDEX `MemberPasswordResetRequest_tokenHash_key` (`tokenHash`),
  INDEX `MemberPasswordResetRequest_accountId_requestedAt_id_idx` (`accountId`, `requestedAt`, `id`),
  INDEX `MemberPasswordResetRequest_status_expiresAt_idx` (`status`, `expiresAt`),
  INDEX `MemberPasswordResetRequest_requestedAt_id_idx` (`requestedAt`, `id`),
  PRIMARY KEY (`id`),
  CONSTRAINT `MemberPasswordResetRequest_accountId_fkey` FOREIGN KEY (`accountId`) REFERENCES `MemberAccount` (`id`) ON DELETE CASCADE ON UPDATE RESTRICT
) ENGINE=InnoDB DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_bin;
