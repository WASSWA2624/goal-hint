"""Regenerate the IANA time zone -> country table used for approximate analytics locations.

Usage: python scripts/generate-analytics-timezones.py [ZONEINFO_DIR]
The directory must contain the public-domain tz database files zone.tab and tzdata.zi
(Git for Windows ships them in /mingw64/share/zoneinfo; Linux in /usr/share/zoneinfo).
"""
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parent.parent
TARGET = ROOT / "src/server/analytics/analytics-timezones.ts"


def main() -> None:
    source = Path(sys.argv[1]) if len(sys.argv) > 1 else Path("/usr/share/zoneinfo")
    zones: dict[str, str] = {}
    version = "unknown"
    for line in (source / "zone.tab").read_text(encoding="utf-8").splitlines():
        if line.startswith("#") or not line.strip():
            continue
        country, _, name, *_ = line.split("\t")
        zones[name] = country
    links: dict[str, str] = {}
    for line in (source / "tzdata.zi").read_text(encoding="utf-8").splitlines():
        if line.startswith("# version "):
            version = line.removeprefix("# version ").strip()
        if line.startswith("L "):
            _, target, alias = line.split()
            links[alias] = target
    # zone.tab keeps a country for every merged zone (Europe/Amsterdam stays NL), so it wins over link targets.
    for alias, target in links.items():
        while target in links and target not in zones:
            target = links[target]
        if alias not in zones and target in zones:
            zones[alias] = zones[target]
    body = ",\n".join(f'  "{name}": "{country}"' for name, country in sorted(zones.items()))
    TARGET.write_text(
        'import "server-only";\n\n'
        f"// Generated by scripts/generate-analytics-timezones.py from tz database {version} (public domain).\n"
        "// Maps canonical and backward-compatible IANA zone names to ISO 3166-1 alpha-2 countries.\n"
        f"export const timeZoneCountries: Readonly<Record<string, string>> = Object.freeze({{\n{body},\n}});\n",
        encoding="utf-8", newline="\n")
    print(f"Wrote {len(zones)} zones from tz {version} to {TARGET.relative_to(ROOT)}.")


if __name__ == "__main__":
    main()
